def _pipe(d):
    stages = STAGES[d["no"]]

    def draw(cy):
        o = [r(24, cy, 632, 32, "#F4F4F4", INK, 0.5)]
        o.append(t(30, cy + 13, f'域定位：{d["pos"][0]}　｜　{d["pains"]}', 8.4, fill="#1F2328"))
        o.append(t(30, cy + 26, f'规模与验收：{d["sub"]}　｜　{d["pos"][1]}', 8.2, fill="#555555"))
        by = cy + 38
        items = [(f"{MARKS[k]} {s[0]}", list(s[1]), ICONS[k]) for k, s in enumerate(stages)]
        o.append(cards(by, 72, items, gap=8, lsize=8.0, tsize=9.0))
        o.append(ln(X0 + 10, by + 84, 646, by + 84, INK, 1.0, arrow=True))
        for k, s in enumerate(stages):
            o.append(t(X0 + 12 + k * 126, by + 100, "→ " + s[2], 8.0, fill=GREY))
        return "\n".join(o)
    return draw


