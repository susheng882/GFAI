def _heat(cy):
    o = [r(24, cy, 340, 168, "#FFFFFF", INK, 0.9)]
    cw, ch = 54, 27
    for i in range(5):
        for j in range(5):
            risk = (4 - j) * (i + 1)          # 概率 × 影响
            fill = "#E7F2F8" if risk < 6 else ("#C6DEE9" if risk < 12 else "#9AAAB3")
            x, y = 74 + i * cw, cy + 12 + j * ch
            o.append(r(x, y, cw - 3, ch - 3, fill, "#FFFFFF", 0.6))
    o.append(t(60, cy + 22, "5", 8.2, "end", fill=GREY))
    o.append(t(60, cy + 148, "1", 8.2, "end", fill=GREY))
    o.append(t(74, cy + 162, "影\n响", 8.2, fill=GREY))
    o.append(t(240, cy + 176, "发生概率 →", 8.6, "middle", fill=GREY))
    # 风险点
    pts = [(0, 0, "R1"), (1, 0, "R3"), (2, 1, "R2"), (1, 2, "R7"), (3, 3, "R10"), (2, 2, "R8"), (0, 3, "R5"),
           (3, 1, "R4"), (1, 1, "R6"), (3, 2, "R9")]
    for i, j, lab in pts:
        x, y = 74 + i * cw, cy + 12 + (4 - j) * ch
        o.append(t(x + 24, y + 18, lab, 8.4, "middle", "bold", RED))
    # 右侧分级说明
    o.append(r(378, cy, 278, 168, "#F3FAFD", "#BED3DE", 0.8))
