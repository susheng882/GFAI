def _breakeven(cy):
    o = [r(24, cy, 632, 132, "#FBFDFE", "#BED3DE", 0.8),
         ln(70, cy + 108, 636, cy + 108, INK, 0.9, arrow=True),
         ln(70, cy + 108, 70, cy + 14, INK, 0.9, arrow=True),
         t(636, cy + 124, "付费用户数 →", 8.8, "end", fill=GREY),
         t(74, cy + 20, "↑ 元/月", 8.8, fill=GREY)]
    # 固定支出线（¥82/月）
    o.append(ln(70, cy + 78, 630, cy + 78, GREY, 1.1, "4 3"))
    o.append(t(624, cy + 88, "固定支出 ¥82/月", 8.2, "end", GREY))
    # 收入线：保守情景客单 ¥10/人·月，20 人 → ¥200
    o.append(ln(70, cy + 108, 630, cy + 40, RED, 1.8))
    o.append(t(626, cy + 34, "收入 ¥10/人·月（保守）", 8.2, "end", RED))
    # 总成本线：固定 ¥82 + 变动 ¥2.5/人
    o.append(ln(70, cy + 78, 630, cy + 62, INK, 1.4))
    o.append(t(626, cy + 58, "总成本", 8.2, "end", INK))
    # 交点：10x = 82 + 2.5x → x ≈ 10.9 人，与产品报告「约 11 个付费用户」一致
    bx = 70 + (11 / 20) * 560
    o.append(circ(bx, cy + 70, 4.2, "#FFFFFF", RED, 1.8))
    o.append(ln(bx, cy + 70, bx, cy + 108, RED, 0.8, "3 3"))
    o.append(t(bx, cy + 48, "盈亏平衡 ≈11 人", 8.8, "middle", "bold", RED))
    o.append(t(96, cy + 100, "0", 8.2, fill=GREY))
    o.append(t(626, cy + 100, "20", 8.2, "end", fill=GREY))
    return "\n".join(o)


