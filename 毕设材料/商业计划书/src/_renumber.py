NO = {o: n for _, o, n in MAP.values()}


def _cn(m):
    k = m.group(1) + "-" + m.group(2)
    return "图 " + NO.get(k, k)


def _en(m):
    k = m.group(1) + "-" + m.group(2)
    return "Fig. " + NO.get(k, k)


def renumber(s):
    s = re.sub(r"图 (\d)-(\d)(?!\d)", _cn, s)
    s = re.sub(r"Fig\. (\d)-(\d)(?!\d)", _en, s)
    return s


def main():
    moved, missing = [], []
    for old, (new, _, _) in MAP.items():
        src = SRC / (old + ".svg")
        if not src.exists():
            missing.append(old)
            continue
        dst = SRC / (new + ".svg")
        dst.write_text(renumber(src.read_text(encoding="utf-8")), encoding="utf-8")
        src.unlink()
        # 清理根目录旧名 PNG，避免与重编后的新名 PNG 并存
        for p in ROOT.glob(old + ".png"):
            p.unlink()
        moved.append(new)
    print("renumbered:", len(moved), "| missing(ok if new-only):", len(missing))
    for n in moved:
        print("  ->", n)


if __name__ == "__main__":
    main()
